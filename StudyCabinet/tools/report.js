function image(file, caption, maxW = 16, maxH = 21) {
  fig++;
  const data = fs.readFileSync(file);
  const w = data.readUInt32BE(16), h = data.readUInt32BE(20);
  let wc = maxW, hc = maxW * h / w;
  if (hc > maxH) { hc = maxH; wc = maxH * w / h; }
  return [
    new Paragraph({ alignment: AlignmentType.CENTER, spacing: { before: 120 }, keepNext: true,
      children: [new ImageRun({ type: 'png', data, transformation: { width: Math.round(wc * CM), height: Math.round(hc * CM) } })] }),
    new Paragraph({ alignment: AlignmentType.CENTER, spacing: { line: 360, after: 160 }, children: [r(`Рисунок ${fig} — ${caption}`)] }),
  ];
}
